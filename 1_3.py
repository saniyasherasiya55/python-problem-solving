#Arithmetic Operators

a = 20
b = 10
print('value of a is :',a)
print('value of a is :',b)
print("Addition of a and b :",a+b)
print("Substraction of a and b :",a-b)
print("Multiplication of a and b :",a*b)
print("Divison of a and b :",a/b)

#Relational Operators
print('a < b :',a<b)
print('a > b :',a>b)
print('a == b :',a==b)
print('a != b :',a!=b)

#Operational 
print(a > 10 and b < 20)
print(a > 10 or b < 20)
print(not(a==b))
